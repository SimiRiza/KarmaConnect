import { Router } from 'express';
import { authenticate, authorize } from '../middleware/auth.js';
import * as ctrl from '../controllers/csrController.js';
const router = Router();
router.use(authenticate, authorize('csr_manager'));
router.get('/me/recommended-projects', ctrl.recommended);
router.get('/me/profile', ctrl.getProfile);
router.put('/me/profile', ctrl.updateProfile);
router.get('/projects', ctrl.discover);
router.post('/match-projects', ctrl.match);
router.get('/projects/:id', ctrl.detail);
router.post('/projects/:id/fund', ctrl.fund);
router.get('/projects/:id/progress', ctrl.progress);
router.get('/fundings', ctrl.fundings);
router.get('/fundings/:id', ctrl.funding);
router.patch('/fundings/:id/withdraw', ctrl.withdraw);
router.get('/reports/portfolio', ctrl.portfolio);
router.get('/reports/:projectId', ctrl.report);
router.get('/dashboard-summary', ctrl.dashboard);
export default router;
